// Turns the files in knowledge/ into src/knowledge.data.js, which the Worker bundles.
// Each file is a plain text or Markdown reference the model should know. An optional first line chooses when it is used:
//   triggers: bond|yield|coupon      (a regular expression, case insensitive)
// With no triggers line the file is added to every question. Run automatically by npm test, npm run deploy and setup.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MAX_PACK_CHARS = 200_000;

export function parsePack(name, raw) {
  const lines = String(raw).replace(/^﻿/, "").split(/\r?\n/);
  let triggers = null;
  const m = lines[0] && lines[0].match(/^triggers:\s*(.+)$/i);
  if (m) {
    triggers = m[1].trim();
    try {
      new RegExp(triggers, "i");
    } catch {
      throw new Error(`knowledge/${name}: the triggers line is not a valid regular expression`);
    }
    lines.shift();
  }
  const text = lines.join("\n").trim();
  if (!text) throw new Error(`knowledge/${name} is empty`);
  if (text.length > MAX_PACK_CHARS) throw new Error(`knowledge/${name} is longer than ${MAX_PACK_CHARS} characters`);
  return { name, triggers, text };
}

export function buildKnowledge(root = ROOT) {
  const dir = join(root, "knowledge");
  let files = [];
  try {
    files = readdirSync(dir).filter((f) => /\.(md|txt)$/i.test(f) && f.toLowerCase() !== "readme.md").sort();
  } catch {
    /* no knowledge folder: nothing to add */
  }
  const packs = files.map((f) => parsePack(f, readFileSync(join(dir, f), "utf8")));
  const out = `// Generated by scripts/build-knowledge.mjs from the files in knowledge/. Do not edit.\nexport const PACKS = ${JSON.stringify(packs, null, 2)};\n`;
  writeFileSync(join(root, "src", "knowledge.data.js"), out);
  return packs.map((p) => p.name);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const names = buildKnowledge();
    console.log(names.length ? `Knowledge packs: ${names.join(", ")}` : "No knowledge packs (add files to knowledge/ to teach the model your material).");
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
